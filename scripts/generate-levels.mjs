// Writes src/games/levels.ts: the level files each game's gameflow names,
// read from the TRX repository, so the shell can tell games apart by the
// files a player brings.
//
// Usage: node scripts/generate-levels.mjs [path to TRX]

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const trx = process.argv[2] ?? '../TRX';
const games = join(trx, 'data/trx/ship/games');
const official = ['tr1', 'tr1-ub', 'tr1-demo-pc', 'tr2', 'tr2-gm', 'tr3', 'tr3-la', 'tr4'];

// The gameflows are JSON with comments and trailing commas.
function parseGameflow(text) {
    const json = text
        .replace(/("(?:[^"\\]|\\.)*")|\/\*[\s\S]*?\*\/|\/\/.*$/gm, (match, string) => string ?? '')
        .replace(/,(\s*[}\]])/g, '$1');
    return JSON.parse(json);
}

// Levels of these types are placeholders, not files a game ships.
const PLACEHOLDER_TYPES = new Set(['current', 'dummy']);

const levels = {};
for (const mod of readdirSync(games).filter((name) => official.includes(name)).sort()) {
    const gameflow = parseGameflow(readFileSync(join(games, mod, 'gameflow.json5'), 'utf8'));
    const entries = [
        gameflow.title,
        ...(gameflow.levels ?? []),
        ...(gameflow.cutscenes ?? []),
        ...(gameflow.demos ?? []),
    ];
    const names = new Set();
    for (const entry of entries) {
        if (typeof entry?.path !== 'string' || PLACEHOLDER_TYPES.has(entry.type)) continue;
        if (!/\.(phd|tr2|tr4)$/i.test(entry.path)) continue;
        names.add(entry.path.slice(entry.path.lastIndexOf('/') + 1).toLowerCase());
    }
    levels[mod] = [...names].sort();
}

const body = Object.entries(levels)
    .map(([mod, names]) => `    '${mod}': [\n${names.map((name) => `        '${name}',`).join('\n')}\n    ],`)
    .join('\n');
writeFileSync(
    'src/games/levels.ts',
    `// Generated by scripts/generate-levels.mjs from the TRX gameflows. Do not edit.\n\n` +
        `/** The level files each game's gameflow names, in lower case. */\n` +
        `export const GAME_LEVELS: Record<string, readonly string[]> = {\n${body}\n};\n`,
);
console.log(Object.entries(levels).map(([mod, names]) => `${mod}: ${names.length}`).join(', '));
